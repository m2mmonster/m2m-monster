// Generates apps/api/src/terms-text.ts from the approved terms (docs/terms-en.md), so the
// production /terms.json serves that file and nothing written by hand (D56).
//   node scripts/gen-terms.mjs
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = "docs/terms-en.md";
const TARGET = "apps/api/src/terms-text.ts";

const text = readFileSync(SOURCE, "utf8").replace(/\r\n/g, "\n");
const [title, updated] = text.split("\n");
const match = /^Last updated: (\w+ \d{1,2}, \d{4})$/.exec(updated ?? "");
if (!match) throw new Error(`${SOURCE}: second line must be "Last updated: <Month D, YYYY>"`);
const date = new Date(`${match[1]} 00:00:00 UTC`);
if (Number.isNaN(date.getTime())) throw new Error(`${SOURCE}: invalid date ${match[1]}`);
const version = date.toISOString().slice(0, 10);

writeFileSync(
  TARGET,
  `// Generated by scripts/gen-terms.mjs from ${SOURCE}. Do not edit: change the source file and
// run \`pnpm terms\`.

export const TERMS_TITLE = ${JSON.stringify(title)};
export const TERMS_VERSION = ${JSON.stringify(version)};
export const TERMS_TEXT = ${JSON.stringify(text)};
`,
);
console.log(`${TARGET}: version ${version}`);
